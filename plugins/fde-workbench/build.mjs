/**
 * Build the browser half into one `client.js`.
 *
 * DSH serves `exports["./client"]` as a single bundle whose only contract is
 * `window.__ModuleLoader__.load({ id, factory })`. Rollup produces a CJS
 * closure; this script wraps it so the factory receives the Loader's own
 * `require` for `react` and DSH client packages.
 */
import { readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { rollup } from 'rollup'

const root = dirname(fileURLToPath(import.meta.url))
const PLUGIN_ID = '@acme-community/fde-workbench'
const MAX_BYTES = 2 * 1024 * 1024
const EXTERNALS = new Set(['react', 'react-dom'])

/** Inline a stylesheet as a default-exported string. */
const cssText = {
  name: 'fde-workbench-css-text',
  transform(code, id) {
    if (!id.endsWith('.css')) return null
    return { code: `export default ${JSON.stringify(code)}`, map: null }
  },
}

/** Indent a block by two spaces for the wrapper. */
function indent(text) {
  return text
    .split('\n')
    .map(line => (line === '' ? '' : `    ${line}`))
    .join('\n')
}

/** Fail the build when the artifact cannot satisfy the Loader contract. */
function verify(code) {
  if (!code.includes('window.__ModuleLoader__.load')) throw new Error('bundle does not register with __ModuleLoader__')
  if (!code.includes(PLUGIN_ID)) throw new Error('bundle does not carry the package id')
  if (/(^|\n)\s*(import|export)\s/.test(code)) throw new Error('bundle still contains ESM syntax')
  const bytes = Buffer.byteLength(code, 'utf8')
  if (bytes > MAX_BYTES) throw new Error(`bundle is too large: ${bytes} bytes`)
  return bytes
}

const input = join(root, 'src/client/index.js')
const bundle = await rollup({
  input,
  external: specifier => EXTERNALS.has(specifier) || specifier.startsWith('@deepseek-ai/'),
  plugins: [cssText],
  onwarn(warning, warn) {
    if (warning.code === 'THIS_IS_UNDEFINED') return
    warn(warning)
  },
})
const generated = await bundle.generate({
  format: 'cjs',
  exports: 'default',
  inlineDynamicImports: true,
  sourcemap: false,
})
await bundle.close()
const chunk = generated.output.find(item => item.type === 'chunk')
if (chunk === undefined) throw new Error('rollup produced no chunk')

const body = `/* Generated by build.mjs — edit src/client instead. */\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(PLUGIN_ID)},\n  factory(require) {\n    const module = { exports: {} }\n    const exports = module.exports\n${indent(chunk.code)}\n    return module.exports\n  },\n})\n`
const bytes = verify(body)
await writeFile(join(root, 'client.js'), body, 'utf8')
const { size } = await stat(join(root, 'client.js'))
console.log(`fde-workbench: wrote client.js (${size} bytes, limit ${MAX_BYTES})`)
